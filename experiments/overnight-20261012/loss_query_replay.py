"""Text-only CPU BM25 replay on the48 known CDL loss cases; no generation."""
import json
import sqlite3
import statistics
from collections import defaultdict

from offline import ranking
from worker import BASE, OUTPUT, ROOT, read, save


def main():
    aliases = read(BASE / "enterprise/duplicate-id-aliases.json")
    cases = read(OUTPUT / "failure-analysis.json")["cdl_losses"]["cases"]
    records = []
    with sqlite3.connect((BASE / "enterprise/corpus.sqlite").resolve().as_uri() + "?mode=ro", uri=True) as db:
        db.execute("PRAGMA cache_size=-16000")
        for case in cases:
            original = case["searches"][0] if case["searches"] else None
            gold = {aliases.get(doc, doc) for doc in case["gold_ids"]}
            row = {"id": case["id"], "category": case["category"], "gold_ids": sorted(gold),
                   "original_arguments": original, "trace": case["trace"], "arms": {}}
            for arm, query in (("natural", case["question"]), ("historical_first", original["query"] if original else "")):
                ids = [hit["document_id"] for hit in ranking(db, query, 2, False, aliases)]
                row["arms"][arm] = {"query": query, "ranked": ids,
                                     **{f"recall{k}": len(gold & set(ids[:k])) / len(gold) if gold else None for k in (5,20)}}
            records.append(row)
    groups = defaultdict(list)
    for row in records:
        if row["gold_ids"]:
            groups["all"].append(row)
            groups[row["category"]].append(row)
    result = {"kind": "known_cdl_losses_query_text_replay", "date": "2026-10-13", "model_calls": 0,
              "questions": len(records), "no_gold": sum(not r["gold_ids"] for r in records),
              "missing_first_query": sum(r["original_arguments"] is None for r in records),
              "settings": "Both arms global BM25 title2/porter unicode61, OR matching, offset0, canonical20 distinct docs. Original scope/all_terms/limit ignored in both arms; varies query text only, not a recreation of the old hybrid ranking.",
              "groups": {}, "cases": records,
              "limits": ["Selected after seeing failures on known400; not a promotion set or causal answer-quality estimate.",
                         "Historical first query was generated by astra; not the new sol trajectory.",
                         "Recall by reference ID does not prove required facts exposed or correct body version.",
                         "No model call, index write, parser change or default policy promotion."]}
    for name, rows in groups.items():
        result["groups"][name] = {"n": len(rows), "arms": {}}
        for arm in ("natural", "historical_first"):
            result["groups"][name]["arms"][arm] = {f"recall{k}": statistics.mean(r["arms"][arm][f"recall{k}"] for r in rows) for k in (5,20)}
        for k in (5,20):
            deltas = [r["arms"]["natural"][f"recall{k}"] - r["arms"]["historical_first"][f"recall{k}"] for r in rows]
            result["groups"][name][f"paired{k}"] = {"gain": statistics.mean(deltas), "wins": sum(d>0 for d in deltas),
                                                      "losses": sum(d<0 for d in deltas), "ties": sum(d==0 for d in deltas)}
    save(OUTPUT / "loss-query-replay.json", result)
    save(ROOT / "evidence/loss-query-replay-20261013.json", result)
    print(json.dumps({k:v for k,v in result.items() if k!="cases"},ensure_ascii=False,indent=2))


if __name__ == "__main__":
    main()
